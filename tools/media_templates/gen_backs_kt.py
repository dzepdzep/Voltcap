# Update 170: writes ui/MediaBacks.kt from backs.json (backs_build.py).
import json, sys
T = json.load(open('backs.json'))
out = sys.argv[1] if len(sys.argv) > 1 else 'MediaBacks.kt'
def fa(v): return 'floatArrayOf(' + ', '.join(f'{x}f' for x in v) + ')'
rows = []
for p, t in T.items():
    wins = 'listOf(' + ', '.join(fa(w) for w in t['wins']) + ')' if t['wins'] else 'emptyList()'
    band = fa(t['band']) if t['band'] else 'null'
    rows.append(f'        "{p}" to BackTpl(R.drawable.tpl_back_{p.lower()}, {t["aspect"]}f, {wins}, {band}, {str(t["overArt"]).lower()}, {str(t["ink"] == "dark").lower()})')
kt = '''package com.shelf.launcher.ui

import com.shelf.launcher.R

/*
 * GENERATED by tools/media_templates/gen_backs_kt.py from the template pack's back covers (backs_build.py). Don't edit by
 * hand. Update 170: the printed backs of the 3D cases (PrintedBacks.kt).
 */

/**
 * A console's case back: the picture ([res], its width / height), its screenshot windows and the plain band where the
 * screenshots and the description are printed (fractions l, t, r, b), whether that band lies over the game's art
 * ([overArt]: the picture is see-through there) and whether its ink is dark.
 */
internal class BackTpl(
    val res: Int, val aspect: Float, val wins: List<FloatArray>, val band: FloatArray?, val overArt: Boolean, val darkInk: Boolean
)

internal object MediaBacks {
    fun of(platform: String?): BackTpl? = platform?.let { all[it] }

    private val all: Map<String, BackTpl> = mapOf(
''' + ',\n'.join(rows) + '''
    )
}
'''
open(out, 'w').write(kt)
print(len(rows), 'backs')
