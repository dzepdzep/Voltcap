"""Update 58: each console's real cover template (front frame with a see-through art window + spine) from the template pack.
Usage: python covers.py [PACK_DIR] [RES_OUT_DIR] [KT_OUT_FILE]   (defaults point at the pack / project_copy on Windows)
Writes res/drawable-nodpi/cov_front_<p>.webp, cov_spine_<p>.webp and ui/MediaCovers.kt (don't edit that by hand)."""
import os, sys, numpy as np, cv2
from PIL import Image
from covmap import C
PACK = sys.argv[1] if len(sys.argv) > 1 else r'C:\Users\User\Downloads\Templates'
OUT = sys.argv[2] if len(sys.argv) > 2 else r'project_copy\app\src\main\res\drawable-nodpi'
KT = sys.argv[3] if len(sys.argv) > 3 else r'src_copy\ui\MediaCovers.kt'
os.makedirs(OUT, exist_ok=True)

def window(front):
    """The art window: the biggest see-through area of the front frame (bounds as l, t, r, b fractions)."""
    a = np.array(front)[:, :, 3]
    t = (a < 128).astype(np.uint8)
    n, lab, st, _ = cv2.connectedComponentsWithStats(t, connectivity=4)
    if n <= 1: return [0.0, 0.0, 1.0, 1.0]
    k = 1 + int(np.argmax(st[1:, 4])); x, y, w, h, ar = st[k]
    H, W = a.shape
    if w > 0.9 * W and h > 0.9 * H: return [0.0, 0.0, 1.0, 1.0]
    return [round(x / W, 4), round(y / H, 4), round((x + w) / W, 4), round((y + h) / H, 4)]

def save(im, name, maxdim):
    im = im.copy(); im.thumbnail((maxdim, maxdim), Image.LANCZOS)
    im.save(os.path.join(OUT, name + '.webp'), 'WEBP', quality=90, method=4)

lines = []
for p, (folder, fr, sp) in C.items():
    d = os.path.join(PACK, *folder.split('/'), 'cover')
    f = Image.open(os.path.join(d, fr)).convert('RGBA'); s = Image.open(os.path.join(d, sp)).convert('RGBA')
    r = p.lower(); win = window(f)
    save(f, f'cov_front_{r}', 560); save(s, f'cov_spine_{r}', 700)
    fa = round(f.width / f.height, 4); sa = round(s.width / s.height, 4)
    lines.append(f'        "{p}" to CoverTpl(R.drawable.cov_front_{r}, {fa}f, floatArrayOf({", ".join(f"{v}f" for v in win)}), R.drawable.cov_spine_{r}, {sa}f),')
    print(p, fa, sa, win)
