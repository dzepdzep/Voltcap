import json
T=json.load(open('table.json'))
def fa(v): return 'floatArrayOf(' + ', '.join(f'{float(x)}f' for x in v) + ')'
def flat(q): return [c for p in q for c in p]
lines=[]
for e in T:
    p=e['p']; r=p.lower()
    def cart(k,res,mres):
        c=e.get(k)
        if not c: return 'null'
        return f'CartTpl(R.drawable.{res}_{r}, R.drawable.{mres}_{r}, {c["aspect"]}f, {fa(c["win"])})'
    disc=f'R.drawable.tpl_disc_{r}' if e.get('disc') else 'null'
    b=e.get('box')
    if b:
        spine=f'R.drawable.tpl_spine_{r}' if b.get('spineTex') else 'null'
        fr=b.get('frame')
        frame=f'R.drawable.tpl_front_{r}, {fr["aspect"]}f, {fa(fr["win"])}' if fr else 'null, 1f, null'
        box=f'BoxTpl(R.drawable.tpl_box_{r}, {b["aspect"]}f, {fa(flat(b["front"]))}, {fa(flat(b["spine"]))}, {"true" if b["hspine"] else "false"}, {spine}, {frame})'
    else: box='null'
    lines.append(f'        "{p}" to MediaTpl({cart("cart","tpl_cart","tpl_cartm")}, {cart("label","tpl_cartl","tpl_cartlm")}, {disc}, {box}),')
