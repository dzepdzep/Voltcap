#!/usr/bin/env python3
"""Writes src_copy/ui/CustomPackShaders.kt: the shader text custom theme / visualizer packs are built on.

A pack only supplies one function (voltScene / voltViz). Voltcap puts that between

    PRELUDE       - tools/themes/scenes/_prelude.agsl, word for word (uniforms, noise, glow, finish ...)
    VIZ_EXTRAS    - the music helpers a visualizer may use, taken from _reactive.agsl: its plain uniforms
                    (no pictures) and room / waveX / eqBand / eqAt / vivid / paletteField
    wrapper       - main(), which calls the pack's function, keeps every uniform alive, and finishes the colour

so a pack can never declare its own uniforms or pictures, and the app only ever sets the values listed here
(on Android 13 setting a uniform the compiler dropped aborts the app - see docs/claude/themes.md).

Run after editing _prelude.agsl or _reactive.agsl:   python tools/themes/gen_pack_prelude.py [src_copy]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCENES = os.path.join(HERE, "scenes")
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src_copy")
OUT = os.path.join(SRC, "ui", "CustomPackShaders.kt")

# Plain (non-picture) uniforms of the music scenes that a visualizer pack gets.
VIZ_UNIFORMS = ["uBass", "uMid", "uHigh", "uBeatAge", "uPlaying", "uIntensity", "uEqA", "uEqB",
                "uWaveY", "uWaveH", "uWaveX", "uPlayT", "uBassT", "uMidT", "uHighT"]
# Helper functions copied from _reactive.agsl (none of them touches a picture).
VIZ_FUNCS = ["room", "waveX", "eqBand", "eqAt", "vivid", "paletteField"]


def read(name):
    with open(os.path.join(SCENES, name), encoding="utf-8") as f:
        return f.read()


def extract_function(src, name):
    m = re.search(r"^[A-Za-z_]\w*\s+" + name + r"\s*\([^)]*\)\s*\{", src, flags=re.M)
    if not m:
        raise SystemExit("function %s not found in _reactive.agsl" % name)
    # include the comment lines right above it
    start = m.start()
    lines_before = src[:start].split("\n")
    k = len(lines_before) - 1
    while k > 0 and lines_before[k - 1].lstrip().startswith("//"):
        k -= 1
    start = len("\n".join(lines_before[:k])) + (1 if k else 0)
    i = src.index("{", m.end() - 1)
    depth = 0
    while True:
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
        i += 1


def uniform_line(src, name):
    m = re.search(r"^uniform\s+\w+\s+" + name + r";[^\n]*$", src, flags=re.M)
    if not m:
        raise SystemExit("uniform %s not found in _reactive.agsl" % name)
    return m.group(0)


def kt_raw(text):
    if '"""' in text or "$" in text:
        raise SystemExit("prelude text contains a quote triple or a dollar sign")
    return '"""' + text.rstrip() + '\n"""'


def main():
    prelude = read("_prelude.agsl")
    reactive = read("_reactive.agsl")
    extras = "// --- music helpers (visualizer packs) ---\n"
    extras += "\n".join(uniform_line(reactive, u) for u in VIZ_UNIFORMS) + "\n\n"
    extras += "\n\n".join(extract_function(reactive, f) for f in VIZ_FUNCS) + "\n"
    kt = [
        "package com.shelf.launcher.ui",
        "",
        "// GENERATED by tools/themes/gen_pack_prelude.py from scenes/_prelude.agsl and _reactive.agsl - edit those, then re-run.",
        "",
        "/** The shared shader text custom packs are built on (see CustomPackRules.buildSource). */",
        "internal object CustomPackShaders {",
        "    const val PRELUDE = " + kt_raw(prelude),
        "",
        "    const val VIZ_EXTRAS = " + kt_raw(extras),
        "",
        "    /** Plain uniforms a visualizer pack gets on top of the theme ones. */",
        "    val VIZ_UNIFORMS: List<String> = listOf(" + ", ".join('"%s"' % u for u in VIZ_UNIFORMS) + ")",
        "}",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(kt))
    print("wrote", OUT)


main()
