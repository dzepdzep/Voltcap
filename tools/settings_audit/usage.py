#!/usr/bin/env python3
"""Phase 10 (12 Nov): how each Features pref is USED - every reference classified as a read or a write, from the source.
Read-only analysis: nothing is renamed, deleted or migrated. Usage: usage.py SRC_ROOT OUT.md OUT.json
Classes: NORMAL (read, and written or handed to a settings row), PASSED-ONLY (only handed to a row / helper that reads and writes it),, WRITE-ONLY (written, never read: candidates to retire, owner's call), NEVER-WRITTEN
(read, only changed by import / layout presets / QA hooks: a constant in practice), UNUSED (neither, beyond its declaration).
Every pref is also written in bulk by Features.reload / import / layout presets (Features.all) - not counted here."""
import re, sys, os, json, collections
root, out_md, out_json = sys.argv[1], sys.argv[2], sys.argv[3]
feat_path = os.path.join(root, 'data/Features.kt')
feat = open(feat_path).read()
decl = re.compile(r'^\s*(?:private\s+|internal\s+)?val\s+(\w+)\s*=\s*(BoolPref|IntPref|EnumPref|StringPref|SetPref|BoxRowsPref)\("([^"]+)"', re.M)
prefs = [dict(name=m.group(1), type=m.group(2), key=m.group(3)) for m in decl.finditer(feat)]
files = {}
for dp, _, fs in os.walk(root):
    for f in fs:
        if f.endswith('.kt') and f != 'ThemeShaders.kt':
            p = os.path.join(dp, f); files[os.path.relpath(p, root)] = open(p, errors='ignore').read()
WRITE = re.compile(r'^\s*(?:\.state)?\.value\s*=(?!=)|^\.toggle\(|^\.setByName\(|^\.set\(|^\.write\(')
READ = re.compile(r'^\.(?:state\.value|value|state|asFlow\(\)|name\b)')
out = []
for p in prefs:
    rx = re.compile(r'(?:Features\.|\b[Ff]\.|(?<![\w.]))' + re.escape(p['name']) + r'(?=[.\s)\],]|$)')
    reads, writes, passes, rf, wf = 0, 0, 0, set(), set()
    for f, s in files.items():
        for m in rx.finditer(s):
            # skip the declaration itself
            line_start = s.rfind('\n', 0, m.start()) + 1
            line = s[line_start:s.find('\n', m.end())]
            if re.match(r'\s*(?:private\s+|internal\s+)?val\s+' + re.escape(p['name']) + r'\s*=', line): continue
            rest = s[m.end():m.end() + 40]
            if WRITE.match(rest): writes += 1; wf.add(f)
            elif READ.match(rest): reads += 1; rf.add(f)
            elif rest[:1] in ')],' or rest.strip()[:1] in ')],': passes += 1; wf.add(f)   # the pref object handed to a row / helper (it may write it)
            else: reads += 1; rf.add(f)
    cls = ('NORMAL' if reads and (writes or passes) else 'PASSED-ONLY' if passes and not reads else 'WRITE-ONLY' if writes else 'NEVER-WRITTEN' if reads else 'UNUSED')
    out.append(dict(p, reads=reads, writes=writes, passes=passes, read_files=sorted(rf)[:6], write_files=sorted(wf)[:6], cls=cls))
# known overlapping groups: several prefs deciding one thing (each group is resolved by ONE function, named here)
GROUPS = [
    ('What A opens (popup style)', ['popup_style_by_layout', 'classic_window_layouts', 'win_banner', 'win_motion', 'win_scenes'],
     'PopupStyle.current / winPresentation (WinPageFlow.kt); WinPresentationTest covers the combinations'),
    ('A starts the game (layouts that once launched on A)', ['cards_a_plays', 'pq_a_plays'], 'popup-first defaults off (PopupFirstDefaultsTest)'),
    ('Box sides', ['box_sides', 'box_sides_chosen', 'm467_box_sides_done'], 'box_sides decides; box_sides_chosen is write-only (kept); m467 is a one-time migration marker'),
]
keys = {p['key']: p for p in out}
json.dump(dict(prefs=out, groups=[dict(title=t, keys=k, resolved_by=r) for t, k, r in GROUPS]), open(out_json, 'w'), indent=1)
c = collections.Counter(p['cls'] for p in out)
with open(out_md, 'w') as w:
    w.write('# Settings usage (generated, read-only)\n\nGenerated by `tools/settings_audit/usage.py` from `data/Features.kt` and every source file. '
            'Nothing was renamed, deleted or migrated. A reference is a write when it assigns `.value` / `.state.value` or calls `toggle` / `setByName`; '
            'everything else is a read. Bulk reads / writes through `Features.all` (import, layout presets, reload) are not counted.\n\n')
    w.write('Totals: ' + ', '.join('%s %d' % kv for kv in sorted(c.items())) + ' (of %d prefs).\n\n' % len(out))
    w.write('## Overlapping groups (one decision each)\n\n| Decision | Keys | Resolved by |\n|---|---|---|\n')
    for t, k, r in GROUPS:
        w.write('| %s | %s | %s |\n' % (t, ', '.join('`%s`%s' % (x, '' if x in keys else ' (marker)') for x in k), r))
    for cls in ('WRITE-ONLY', 'UNUSED', 'NEVER-WRITTEN', 'PASSED-ONLY'):
        rows = [p for p in out if p['cls'] == cls]
        w.write('\n## %s (%d)\n\n| Key | Name | Reads | Writes | Passed | Where |\n|---|---|---|---|---|---|\n' % (cls, len(rows)))
        for p in rows:
            w.write('| `%s` | %s | %d | %d | %d | %s |\n' % (p['key'], p['name'], p['reads'], p['writes'], p['passes'], ', '.join(p['read_files'] or p['write_files'])))
print(dict(c))
