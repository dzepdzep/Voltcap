#!/usr/bin/env python3
"""Phase 9 (12 Nov): the 53-layout popup audit matrix, generated from the source (HomeLayout, winSceneFor, NATIVE_PAGE_SCENES,
MORE_SCENES) plus the hand-kept status file tools/popup_audit/status.json. Usage: layout_matrix.py [repo root] > docs/LAYOUT_MATRIX.md
Status labels: NOT STARTED / INVESTIGATED / IMPLEMENTED / PC TESTED / HARDWARE PENDING / HARDWARE VERIFIED (never set without device evidence)."""
import json, os, re, sys
root = sys.argv[1] if len(sys.argv) > 1 else '.'
ui = os.path.join(root, 'app/src/main/java/com/shelf/launcher/ui')
def read(p): return open(p, encoding='utf-8').read()
s = read(os.path.join(root, 'app/src/main/java/com/shelf/launcher/data/AppearanceStore.kt'))
i = s.index('enum class HomeLayout(val label: String) {'); body = s[i:s.index('\n}\n', i)]
layouts = re.findall(r'^\s*([A-Z_0-9]+)\("([^"]*)"\)', body, re.M)
w = read(os.path.join(ui, 'WinScenes.kt'))
j = w.index('internal fun winSceneFor(layout: HomeLayout): WinScene? = when (layout) {'); f = w[j:w.index('\n}\n', j)]
scene = {}; other = None
for line in f.split('\n')[1:]:
    m = re.match(r'\s*(.+?)\s*->\s*(.+)', line)
    if not m: continue
    rhs = m.group(2).strip().replace('WinScene.', '')
    if m.group(1).strip() == 'else': other = rhs
    for l in re.findall(r'HomeLayout\.([A-Z_0-9]+)', m.group(1)): scene[l] = rhs
pf = read(os.path.join(ui, 'WinPageFlow.kt'))
_np = pf.index('internal val NATIVE_PAGE_SCENES'); native = set(re.findall(r'WinScene\.([A-Z_]+)', pf[_np:pf.index('\n\n', _np)]))  # (529k: the set spans lines)
gw = read(os.path.join(ui, 'GameWindow.kt'))
k = gw.index('internal val MORE_SCENES = setOf('); more = set(re.findall(r'WinScene\.([A-Z_]+)', gw[k:gw.index('\n)\n', k)]))
st = json.load(open(os.path.join(root, 'tools/popup_audit/status.json'), encoding='utf-8'))
LABELS = ['NOT STARTED', 'INVESTIGATED', 'IMPLEMENTED', 'PC TESTED', 'HARDWARE PENDING', 'HARDWARE VERIFIED']
print('# Popup audit matrix — all %d layouts (generated)\n' % len(layouts))
print('Generated by `tools/popup_audit/layout_matrix.py` from the source + `tools/popup_audit/status.json`. Do not edit by hand.')
print('Status labels: ' + ' / '.join(LABELS) + '. HARDWARE VERIFIED is only ever set with device evidence, and means functional only - visual approval is the owner\'s, listed in the note.\n')
print('Shared for every layout (PC TESTED, `WinPresentationTest`, `NativePageFocusTimingTest`, `InertControlsTest`): one presentation')
print('decision (`winPresentation`); B from a page focuses its opener directly (Play never lit after B); popup-first (A opens the window).\n')
print('| # | Layout | Name | Window scene | Pages | More | Status | Notes |')
print('|---|---|---|---|---|---|---|---|')
counts = {}
for n, (l, lab) in enumerate(layouts, 1):
    sc = scene.get(l, other) or 'none (plain / TV window)'
    pages = 'native (own)' if sc in native else ('own options list' if sc == 'CROSS_OPTIONS' else ('shared page' if sc != 'none (plain / TV window)' else 'plain window pages'))
    e = st.get(l, st['_default'])
    for x in e['status']: assert x in LABELS, (l, x)
    counts[e['status'][-1]] = counts.get(e['status'][-1], 0) + 1
    print('| %d | `%s` | %s | `%s` | %s | %s | %s | %s |' % (n, l, lab, sc, pages, 'yes' if sc in more else '', ' → '.join(e['status']), e.get('note', '')))
# exact coverage, machine-readable (tools/popup_audit/coverage.json): which real-window tests cover each layout
shelf_text = {'SHELF', 'STACKS', 'STORAGE', 'NIGHT', 'TILES', 'BLADES'}
cov = {}
for l, lab in layouts:
    sc = scene.get(l, other)
    tests = ['WinFocusRoboTest.opensOnPlayAndPlayWorksAfterTheGuard', 'WinFocusRoboTest.backFromOptionsLandsOnTheOpenerOnEveryFrame',
             'WinFocusRoboTest.rapidBThenANeverStartsTheGame', 'WinFocusRoboTest.bInTheMiddleOfAPageChange', 'WinFocusRoboTest.anASoonAfterBActsOnTheOpener',
             'WinFocusRoboTest.aOrBWhileOpeningNeverStartsTheGame', 'WinFocusRoboTest.rapidBABAOnTheMainPageNeverStartsTheGame',
             'WinPresentationTest (all pref combinations)']
    if sc in native: tests.append('WinFocusRoboTest.bumpersWalkThePagesAndFocusStaysOnAVisibleControl')
    if l in shelf_text: tests.append('ShelfTextRoboTest (x1.0/x1.3, short/long title, 0/160/9999 achievements)')
    if l in ('CLASSIC', 'SHELF', 'STORAGE'): tests.append('WinFocusRoboTest plain window (layout windows off)')
    if l in ('SHELF', 'STACKS'): tests.append('ShelfHandOverRobustTest / ShelfCaseHandOverTest (case flight gate)')
    if l == 'SHELF': tests.append('ShelfCase3DTest / ShelfCase3DRenderTest (experimental 3D case, off by default)')
    e = st.get(l, st['_default'])
    cov[l] = dict(name=lab, scene=sc, pages=('native' if sc in native else 'shared'), status=e['status'], tests=tests, hardware=e.get('hardware', 'none'))
json.dump(cov, open(os.path.join(root, 'tools/popup_audit/coverage.json'), 'w'), indent=1, ensure_ascii=False)
print('\nLatest status per layout: ' + ', '.join('%s %d' % (k2, v) for k2, v in sorted(counts.items(), key=lambda kv: LABELS.index(kv[0]))))

# 529j (owner, 13 Nov: "all 53 layouts ... separate statuses for game window, native pages, opening, closing / return,
# controller, small screen, hardware - do not mark a layout complete just because a shared popup works"): the overhaul table.
ov = json.load(open(os.path.join(root, 'tools/popup_audit/overhaul.json'), encoding='utf-8'))
pk = gw[gw.index('internal val PICKUP_CARD_LAYOUTS'):]; pk = pk[:pk.index('\n')]
pickup = {l: 'card / case flight (window out of the picked piece, piece hidden in the home)' for l in re.findall(r'HomeLayout\.([A-Z_]+)', pk)}
for l in ('SHELF', 'STACKS'): pickup[l] = 'case flight (the case itself flies out and back; home copy hidden)'
pickup['ORBIT'] = 'disc flight (the disc flies to the terminal and back)'
# Scenes that open out of the picture itself (a physical piece only when Inspect asks for it) - GameWindow's sceneOwnsOpen.
so = gw[gw.index('val sceneOwnsOpen = '):]; so = so[:so.index('&& !askedInspect')]
owns_open = set(re.findall(r'WinScene\.([A-Z_]+)', so))
print('\n## Overhaul status per layout - the seven checks (529j)\n')
print('A layout is COMPLETE only when every column is done: own window, native pages, opening and return motion right for what')
print('the home shows (a real pickup where it shows physical games), controller rules, small screen (KONKR) incl. x1.3,')
print('hardware on both handhelds, and your visual approval. Facts in `tools/popup_audit/overhaul.json`.\n')
print('| # | Layout | Game window | Native Details / Stats / Options | Opening | Closing / return | Controller | Small screen (KONKR) | Hardware | Your visual approval | Complete |')
print('|---|---|---|---|---|---|---|---|---|---|---|')
done = {k3: 0 for k3 in ('window', 'pages', 'open', 'small', 'hw', 'visual', 'complete', 'pickup_needed', 'pickup_done')}
for n, (l, lab) in enumerate(layouts, 1):
    sc = scene.get(l, other)
    if sc in (None, 'null'): sc = None
    win = ('own (`%s`)' % sc) if sc else 'PLAIN (TV window)'
    pg = 'NATIVE' if sc in native else ('PARTIAL (own Options list)' if sc == 'CROSS_OPTIONS' else 'SHARED page')
    phys = ov['physical'].get(l)
    if l in pickup: op = 'PICKUP: ' + pickup[l]; cl = 'RETURN to its slot'
    elif phys and sc and sc not in owns_open:
        # (GameWindow: the game's own piece - case / disc / cartridge, per the game look - flies out of the home and back.)
        op = 'PICKUP: piece flight (the %s piece, when the game look shows one)' % phys; cl = 'RETURN (piece flies back)'
        pickup[l] = 'piece'
    elif phys: op = 'MISSING pickup (%s; %s)' % (phys, 'opens out of the picture' if sc in owns_open else 'TV window'); cl = 'MISSING return'
    elif sc: op = 'scene motion'; cl = 'scene reverse'
    else: op = 'system'; cl = 'system'
    e = st.get(l, st['_default'])
    hw = 'Flip 2 functional' if 'HARDWARE VERIFIED' in e['status'] else 'none'
    kk = ov['konkr'].get(l, 'NOT CHECKED')
    vis = ov['owner_visual'].get(l, 'pending')
    complete = bool(sc) and sc in native and (l in pickup or not phys) and kk.startswith('PASS') and 'x1.3' in kk and hw != 'none' and vis.startswith('approved')
    done['window'] += bool(sc); done['pages'] += sc in native; done['small'] += kk.startswith('PASS'); done['hw'] += hw != 'none'
    done['visual'] += vis.startswith('approved'); done['complete'] += complete
    done['pickup_needed'] += bool(phys); done['pickup_done'] += bool(phys) and l in pickup
    print('| %d | `%s` %s | %s | %s | %s | %s | PC TESTED | %s | %s | %s | %s |' % (n, l, lab, win, pg, op, cl, kk, hw, vis, 'YES' if complete else 'no'))
print('\nCounts: own window %(window)d / 53; native pages %(pages)d / 53; physical homes with a real pickup %(pickup_done)d / %(pickup_needed)d; '
      'KONKR small-screen pass %(small)d / 53; hardware (Flip 2) %(hw)d / 53; your visual approval %(visual)d / 53; COMPLETE %(complete)d / 53.' % done)
