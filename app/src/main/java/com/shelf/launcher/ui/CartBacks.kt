/*
 * Update 200: the backs of the drawn cartridges (CartShells) — what each real one has on its back, researched from
 * rear photos (and, where none could be found, from written sources only; "verified" says which). Generated from the
 * research data (backs.json, CARTRIDGES.md lists the sources): millimetres on the back seen from behind, connector
 * edge down, origin top-left. The fronts are untouched; only the back is drawn from this.
 */
internal class CartBack(
    val id: String,
    /** "photo" (measured from rear photos), "partial", "unverified", "description". */
    val verified: String,
    /** x, y, head Ø, recess Ø, type (0 cross, 1 tri-wing, 2 security/game bit, 3 slot, 4 clip, 5 torx) — per screw. */
    val screws: FloatArray,
    /** Moulded text: x, y (centre), cap height, rotation, raised 1 / sunken 0 — and [texts]. */
    val textPos: FloatArray,
    val texts: Array<String>,
    /** Sunken areas: x, y, w, h, r, depth. */
    val recesses: FloatArray,
    /** Raised areas: x, y, w, h, r. */
    val raised: FloatArray,
    /** Stickers: x, y, w, h, kind (0 warning, 1 info, 2 serial) — colours in [stickerColours] (bg, ink). */
    val stickers: FloatArray,
    val stickerColours: IntArray,
    /** Seams: x1, y1, x2, y2. */
    val seams: FloatArray,
    /** Connector: x, y, w, h, open (1/0), contacts, separators (1/0); empty = none. */
    val connector: FloatArray,
    /** Other parts: kind (0 notch, 1 grip, 2 tab, 3 hole, 4 window, 5 compartment, 6 flap, 7 port, 8 battery door, 9 lens), x, y, w, h. */
    val extras: FloatArray,
    /** False when the back makes no sense without its maker's markings (the neutral back keeps them then). */
    val neutralOk: Boolean
)

